    /// 查询城市在星野图谱中的 Albers 坐标 (x: 60~590, y: 45~530)
    public static func coordinate(forCode code: String, cityName: String = "") -> (x: Double, y: Double) {
        let trimmed = code.trimmingCharacters(in: .whitespacesAndNewlines)
        if let hit = coordinatesByCode[trimmed] {
            return hit
        }
        if !cityName.isEmpty, let resolved = Self.code(forLocation: cityName), let hit = coordinatesByCode[resolved] {
            return hit
        }
        if trimmed.count >= 2 {
            let capitalCode = String(trimmed.prefix(2)) + "0100"
            if let hit = coordinatesByCode[capitalCode] {
                return hit
            }
        }
        if !cityName.isEmpty {
            for (key, coord) in internationalCoordinates {
                if cityName.contains(key) {
                    return coord
                }
            }
            // 确定性伪随机离散分布（避免所有未匹配境外/未知城市重叠在同一坐标）
            var hasher = Hasher()
            hasher.combine(cityName)
            let hashVal = abs(hasher.finalize())
            let scatterX = 220.0 + Double(hashVal % 260)
            let scatterY = 180.0 + Double((hashVal / 1000) % 220)
            return (scatterX, scatterY)
        }
        return (462.3, 300.0)
    }

    /// 将城市坐标转化为经纬度标尺 (85°E ~ 125°E, 18°N ~ 50°N)，供经纬星野图谱渲染
    public static func lonLat(forCode code: String, cityName: String = "") -> (lon: Double, lat: Double) {
        let pt = coordinate(forCode: code, cityName: cityName)
        let normX = min(max((pt.x - 65.0) / (590.0 - 65.0), 0.02), 0.98)
        let normY = min(max((pt.y - 45.0) / (530.0 - 45.0), 0.02), 0.98)
        let lon = 85.0 + normX * (125.0 - 85.0)
        let lat = 50.0 - normY * (50.0 - 18.0)
        return (lon, lat)
    }
